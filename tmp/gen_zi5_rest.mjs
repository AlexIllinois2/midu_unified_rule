// 三三变调：连续的三声串里，除末位外全部变二声
function sandhi(t) {
  const a = [...t];
  for (let i = 0; i < a.length - 1; i++) {
    if (a[i] === 3 && a[i + 1] === 3) a[i] = 2;
  }
  return a;
}

