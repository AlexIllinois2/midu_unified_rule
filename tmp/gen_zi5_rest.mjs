const keys = new Set(patch.filter(l => l.includes("\t")).map(l => l.split("\t")[0]));

const out = [];
for (const w of words) {
  if ([...w].length !== py[w].length) { console.error("字数不符: " + w); continue; }
  if (keys.has(w)) { console.error("已存在跳过: " + w); continue; }
  const surface = sandhi(py[w]);
  out.push(w + "\t" + surface.map(x => "*" + x).join(" ") + "\tTEXT((" + w + "))");
}
